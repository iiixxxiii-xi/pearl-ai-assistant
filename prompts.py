TRAIT_STRATEGIES = {
    "比较纠结": "客户比较纠结，回复时：减少选项，给1-2个明确推荐，帮客户做决定，语气坚定但温和。",
    "很纠结": "客户非常纠结，回复时：极度简化，只推一个最合适的，直接说'这个最适合你'，帮客户下决心，不要给多个选项。",
    "爽快果断": "客户爽快果断，回复时：不啰嗦不绕弯，直接推最好的，快速促成成交，不要过度介绍。",
}

KNOWLEDGE_STRATEGIES = {
    "完全不懂": "客户对珍珠完全不懂，回复时：反而要多用专业术语（镜面光、正圆、极强光、珠层厚度等）——术语不是用来吓客户的，是用来建立信任的。客户虽然不懂，但听完会觉得你很专业、跟普通卖货的不一样。",
    "略懂一点": "客户对珍珠略懂一点，回复时：用专业术语交流，聊品质判断标准，让客户觉得'这家很懂行'。",
    "很懂行": "客户很懂行，回复时：直接聊专业细节（光泽等级、圆度、瑕疵、珠层厚度、产地等），用行内人的方式对话。",
}

USAGE_STRATEGIES = {
    "自己戴": "客户自己戴，推荐时关注个人风格匹配和日常搭配便利性，不用过度强调包装和面子。",
    "送人": "客户送人，推荐时强调体面、显档次、送礼有面子。如果客户提到送礼对象年龄，根据年龄调整推荐。",
}

QUALITY_STRATEGIES = {
    "好看就行": "客户对品质要求不高，推荐时强调款式好看、戴上显气质，不用过度强调光泽圆度等专业指标。",
    "品质好一点": "客户要品质好一点的，推荐时强调光泽、圆度、瑕疵等核心指标在同价位的优势。",
    "要最好的": "客户要最好的品质，直接推高货：正圆、强光、极微瑕、厚珠层，不要推入门款或中等品质的。",
}


def build_customer_profile_prompt(
    trait: str = "",
    knowledge_level: str = "",
    budget_range: str = "",
    usage: str = "",
    quality: str = "",
) -> str:
    """根据客户画像维度拼接应对策略"""
    parts = []
    if trait.strip():
        if trait.strip() in TRAIT_STRATEGIES:
            parts.append(TRAIT_STRATEGIES[trait.strip()])
        else:
            parts.append(f"客户性格特征：{trait.strip()}。请根据这个性格特点调整回复风格。")
    if knowledge_level.strip() and knowledge_level.strip() in KNOWLEDGE_STRATEGIES:
        parts.append(KNOWLEDGE_STRATEGIES[knowledge_level.strip()])
    if budget_range.strip() and budget_range.strip() in BUDGET_STRATEGIES:
        parts.append(BUDGET_STRATEGIES[budget_range.strip()])
    if usage.strip() and usage.strip() in USAGE_STRATEGIES:
        parts.append(USAGE_STRATEGIES[usage.strip()])
    if quality.strip() and quality.strip() in QUALITY_STRATEGIES:
        parts.append(QUALITY_STRATEGIES[quality.strip()])

    if parts:
        return "【客户画像与应对策略 — 请严格据此调整回复】\n" + "\n".join(parts)
    return ""


